import { chromium } from 'playwright';
const [w,h,dpr,out]=[+process.argv[2],+process.argv[3],+process.argv[4],process.argv[5]];
const b = await chromium.launch({ args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: w, height: h }, deviceScaleFactor: dpr });
const btn = (name, exact = false) => p.getByRole('button', { name, exact }).first();
await p.goto(`http://127.0.0.1:5174/studio.html?user=probe${Date.now()%1000}`);
await p.locator('#boot').waitFor({ state: 'detached', timeout: 20000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: out.replace('.png','_a.png') });
await btn('Open the kiln').click();
await btn('Skip, throw today’s pot').click();
await p.locator('.throw__canvas').waitFor();
await p.waitForTimeout(1200);
const skip = p.getByRole('button', { name: 'Skip', exact: true });
if (await skip.count()) await skip.click();
await p.waitForTimeout(500);
await p.evaluate(() => window.__paanaiVideo.playMaster());
await p.waitForTimeout(9000);
await p.screenshot({ path: out });
console.log(await p.evaluate(()=>[...document.querySelectorAll('.throw *')].filter(e=>e.children.length===0&&e.textContent.trim()).slice(0,30).map(e=>e.className+':'+e.textContent.trim().slice(0,30)).join('\n')));
await b.close();
